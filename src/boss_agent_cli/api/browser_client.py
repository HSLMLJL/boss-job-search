	# ── Core request via browser fetch() ─────────────────────────────

	def request(
		self, method: str, url: str, *, params: dict[str, Any] | None = None, data: dict[str, Any] | None = None
	) -> dict[str, Any]:
		self._ensure_started()
		self._throttle.wait()

		referer = endpoints.REFERER_MAP.get(url, f"{endpoints.BASE_URL}/")

		# Bridge 模式：通过扩展 fetch
		if self._is_bridge and self._bridge_client:
			import urllib.parse

			full_url = url
			if params:
				full_url = f"{url}?{urllib.parse.urlencode(params)}"
			try:
				result = self._bridge_client.fetch_json(
					full_url,
					method=method,
					data=data,
					referer=referer,
				)
			except Exception as exc:
				# Bridge 的连接布尔不证明 workspace/目标页可用。显式来源下把
				# 这种会话级失败归入来源契约；auto 仍保留原异常 → NETWORK_ERROR。
				if self._policy.fail_closed:
					raise BrowserSourceUnavailable(
						self._policy,
						(CHANNEL_BRIDGE,),
						detail="Bridge 已连接但现有页面会话不可用",
					) from exc
				raise
			self._throttle.mark()
			return cast("dict[str, Any]", result)

		# Playwright 模式（CDP 或 headless）
		result = self._page.evaluate(
			"""
			async ({method, url, params, data, referer}) => {
				try {
					let fetchUrl = url;
					if (params && Object.keys(params).length > 0) {
						const sp = new URLSearchParams();
						for (const [k, v] of Object.entries(params)) {
							if (v !== null && v !== undefined) sp.append(k, String(v));
						}
						fetchUrl = url + '?' + sp.toString();
					}

					const options = {
						method: method,
						credentials: 'include',
						headers: {
							'Accept': 'application/json, text/plain, */*',
							'Referer': referer,
							'X-Requested-With': 'XMLHttpRequest',
						},
					};

					if (method === 'POST' && data) {
						options.headers['Content-Type'] = 'application/x-www-form-urlencoded';
						const formData = new URLSearchParams();
						for (const [k, v] of Object.entries(data)) {
							formData.append(k, String(v));
						}
						options.body = formData.toString();
					}

					const resp = await fetch(fetchUrl, options);
					return await resp.json();
				} catch (e) {
					return {code: -1, message: e.message, zpData: {}};
				}
			}
		""",
			{"method": method, "url": url, "params": params or {}, "data": data, "referer": referer},
		)

		self._throttle.mark()
		return cast("dict[str, Any]", result)

	def capture_search_page(
		self,
		query: str,
		city_code: str,
		page: int,
		*,
		reuse_visible_first_page: bool = False,
		page_layout: str = "current_city",
	) -> dict[str, Any]:
		"""Read one validated visible BOSS result page through the Bridge.

		The Bridge reads rendered cards and follows only the site's native next
		link from a durable checkpoint. Python never fabricates paging URLs,
		injects loaders, or falls back to a different channel during a scan.
		"""
		self._ensure_started()
		if not self._is_bridge or self._bridge_client is None:
			raise PageCaptureBridgeRequired()
		# A radar capture always uses the extension-owned dedicated result tab.
		# Keep that tab available after both a completed scan and any ambiguous
		# capture failure: BrowserSession.close() otherwise sends the legacy
		# generic ``close-window`` command, whose target is not radar-scoped.
		# This is intentionally set before validation/bridge status reads so
		# every exit from this radar path has the same non-destructive cleanup.
		self._preserve_bridge_window = True
		if page < 1 or page > 100:
			raise ValueError("page must be between 1 and 100")
		if reuse_visible_first_page and page != 1:
			raise ValueError("reuse_visible_first_page is only valid for page 1")
		if page_layout not in {"current_city", "legacy_spa"}:
			raise ValueError("page_layout must be current_city or legacy_spa")
		if page == 1:
			bridge_status = self._bridge_client.status()
			loaded_version = str((bridge_status or {}).get("extensionVersion") or "")
			if not _bridge_version_at_least(loaded_version, _MIN_RADAR_BRIDGE_VERSION):
				raise RadarBridgeUpgradeRequired(loaded_version)
		self._throttle.wait()
		if page_layout == "legacy_spa":
			search_url = "https://www.zhipin.com/web/geek/jobs?" + urlencode(
				{"city": city_code, "query": query},
			)
			legacy_key = (city_code, query)
			# The visible-capture checkpoint is intentionally keyed by the exact
			# URL observed in the claimed tab. A BOSS SPA URL may retain its
			# query-string order. Continue a successful session with its original
			# command URL; only an explicit continuation in a new session adopts
			# the already-claimed page's URL.
			if page > 1:
				try:
					settled_status = self._bridge_client.radar_tab_status()
				except RuntimeError as exc:
					raise RadarTabNotPrepared("无法读取 Bridge 专用雷达页状态") from exc
				if not _radar_tab_url_matches_search(settled_status, search_url):
					raise RadarTabNotPrepared("专用雷达页与请求的城市或关键词不匹配")
				search_url = self._legacy_capture_urls.get(
					legacy_key,
					cast("str", settled_status["url"]),
				)
		else:
			search_url = f"https://www.zhipin.com/c{city_code}/?" + urlencode({"query": query})
		if page == 1:
			try:
				status = self._bridge_client.radar_tab_status()
			except RuntimeError as exc:
				raise RadarTabNotPrepared("无法读取 Bridge 专用雷达页状态") from exc
			if status.get("prepared") is not True and status.get("automaticPreparation") is not True:
				raise RadarTabNotPrepared(str(status.get("reason") or "尚未绑定搜索结果页"))
		if page_layout == "legacy_spa":
			# An explicit legacy layout stays on its own handler;
			# failures are terminal and never trigger current-city
			# capture or another navigation.
			try:
				result = self._bridge_client.capture_job_list(
					search_url,
					page=page,
					workspace="boss-radar",
					start_fresh=page == 1 and not reuse_visible_first_page,
				)
			except RuntimeError as exc:
				message = str(exc)
				if _is_bridge_account_risk(message):
					self._preserve_bridge_window = True
					raise BridgeAccountRiskError(message) from exc
				raise
		else:
			try:
				result = self._bridge_client.capture_current_job_cards(
					search_url,
					page=page,
					workspace="boss-radar",
					start_fresh=page == 1 and not reuse_visible_first_page,
				)
			except RuntimeError as exc:
				message = str(exc)
				if _is_bridge_account_risk(message):
					self._preserve_bridge_window = True
					raise BridgeAccountRiskError(message) from exc
				# A fresh first-page command has already performed its one ordinary
				# navigation. On some BOSS redirects the extension can report an
				# URL mismatch while the dedicated tab has settled on the exact
				# city/query with an extra transient parameter. Read it once, without
				# another navigation, refresh, or load-more action. Any other error is
				# terminal and is never retried.
				can_read_settled_page = (
					page == 1
					and not reuse_visible_first_page
					and "radar tab URL does not match city and query" in message
				)
				if not can_read_settled_page:
					raise
				try:
					settled_status = self._bridge_client.radar_tab_status()
				except RuntimeError:
					raise exc
				if not _radar_tab_url_matches_search(settled_status, search_url):
					raise
				result = self._bridge_client.capture_current_job_cards(
					search_url,
					page=page,
					workspace="boss-radar",
					start_fresh=False,
				)
		result = _validated_visible_capture(result, page=page)
		if page_layout == "legacy_spa":
			self._legacy_capture_urls[legacy_key] = search_url
		self._throttle.mark()
		return result

	def _capture_visible_first_search_page(
		self,
		query: str,
		city_code: str,
		*,
		original_error: RuntimeError,
	) -> dict[str, Any]:
		"""Recover a fresh first page when only the response listener missed it."""
		if self._bridge_client is None:  # pragma: no cover - guarded by caller
			raise original_error
		expected_city = json.dumps(city_code)
		expected_query = json.dumps(query, ensure_ascii=False)
		state = self._bridge_client.evaluate(
			f"""(() => {{
				{_JOB_LIST_COMPONENT_LOOKUP_JS}
				if (!component) return {{ready: false, reason: 'job list component is unavailable'}};
				const jobs = Array.isArray(component.jobList) ? component.jobList : [];
				const currentPage = Number(component.pageVo?.page || 0);
				const pageSize = Number(component.pageVo?.pageSize || 15);
				const form = component.formData || {{}};
				const matches = String(form.city || '') === {expected_city}
					&& String(form.query || '') === {expected_query};
				const loading = Boolean(component.loading || component.moreLoading);
				if (!matches || currentPage !== 1 || loading) {{
					return {{ready: false, reason: 'visible search state does not match the requested first page'}};
				}}
				return {{
					ready: true,
					items: jobs.slice(0, pageSize),
					hasMore: Boolean(component.hasMore),
				}};
			}})()""",
			workspace="boss-radar",
		)
		if not state.get("ready"):
			raise original_error
		items = state.get("items")
		if not isinstance(items, list):
			raise original_error
		return {"code": 0, "zpData": {"jobList": items, "hasMore": bool(state.get("hasMore"))}}

	def _capture_loaded_search_page(self, query: str, city_code: str, page: int) -> dict[str, Any]:
		"""Ask the already-open BOSS page to load its next normal result batch.

		The current BOSS desktop UI keeps the cumulative result list in its PageJobs
		component.  Programmatic window scrolling does not reliably invoke its loader,
		so subsequent pages call the same ``loadMoreHandle`` method used by the UI and
		read only the newly appended batch.  No direct API request is issued here.
		"""
		if self._bridge_client is None:  # pragma: no cover - guarded by caller
			raise PageCaptureBridgeRequired()
		expected_city = json.dumps(city_code)
		expected_query = json.dumps(query, ensure_ascii=False)
		preflight = self._bridge_client.evaluate(
			f"""(() => {{
				const text = document.body?.innerText || '';
				if (/安全验证|验证码|拖动滑块|环境存在异常|账户存在异常行为|暂时被禁止使用|访问过于频繁|稍后再试/.test(text)
					|| /verify[.]html|[?&]code=(32|36|37)(?:&|$)/.test(location.href)) {{
					return {{ok: false, risk: true, reason: 'BOSS security verification detected'}};
				}}
				{_JOB_LIST_COMPONENT_LOOKUP_JS}
				if (!component) return {{ok: false, reason: 'job list component is unavailable'}};
				const form = component.formData || {{}};
				const pageUrl = new URL(location.href);
				const urlMatches = pageUrl.searchParams.get('city') === {expected_city}
					&& pageUrl.searchParams.get('query') === {expected_query};
				const matches = urlMatches && String(form.city || '') === {expected_city}
					&& String(form.query || '') === {expected_query};
				if (!matches) return {{ok: false, reason: 'visible search state does not match the requested city and query'}};
				return {{ok: true}};
			}})()""",
			workspace="boss-radar",
		)
		if not preflight.get("ok"):
			if preflight.get("risk"):
				self._preserve_bridge_window = True
				raise BridgeAccountRiskError(str(preflight.get("reason") or "BOSS 页面要求安全验证"))
			raise RuntimeError(f"Bridge page loader failed for page {page}: {preflight.get('reason') or 'unknown state'}")
		self._bridge_client.evaluate(
			"window.scrollTo(0, document.documentElement.scrollHeight); "
			"({scrollY, height: document.documentElement.scrollHeight})",
			workspace="boss-radar",
		)
		time.sleep(_JOB_LIST_SCROLL_SETTLE_SECONDS)
		component_deadline = time.monotonic() + _JOB_LIST_COMPONENT_WAIT_SECONDS
		while True:
			trigger = self._bridge_client.evaluate(
				f"""(() => {{
				const text = document.body?.innerText || '';
				if (/安全验证|验证码|拖动滑块|环境存在异常|账户存在异常行为|暂时被禁止使用|访问过于频繁|稍后再试/.test(text)
					|| /verify[.]html|[?&]code=(32|36|37)(?:&|$)/.test(location.href)) {{
					return {{ok: false, risk: true, reason: 'BOSS security verification detected'}};
				}}
				{_JOB_LIST_COMPONENT_LOOKUP_JS}
				if (!component || typeof component.loadMoreHandle !== 'function') {{
					return {{ok: false, reason: 'job list loader is unavailable'}};
				}}
				const form = component.formData || {{}};
				const pageUrl = new URL(location.href);
				const urlMatches = pageUrl.searchParams.get('city') === {expected_city}
					&& pageUrl.searchParams.get('query') === {expected_query};
				const matches = urlMatches && String(form.city || '') === {expected_city}
					&& String(form.query || '') === {expected_query};
				if (!matches) {{
					return {{ok: false, reason: 'visible search state does not match the requested city and query'}};
				}}
				const currentPage = Number(component.pageVo?.page || 0);
				const jobs = Array.isArray(component.jobList) ? component.jobList : [];
				const pageSize = Number(component.pageVo?.pageSize || 15);
				if (currentPage >= {page}) {{
					const start = ({page} - 1) * pageSize;
					const items = jobs.slice(start, start + pageSize);
					if (items.length === 0) {{
						return {{ok: false, reason: 'requested page slice is empty after page state advanced'}};
					}}
					return {{
						ok: true,
						alreadyLoaded: true,
						items,
						hasMore: currentPage > {page} || Boolean(component.hasMore),
					}};
				}}
				if (currentPage !== {page - 1}) {{
					return {{ok: false, reason: 'unexpected current page ' + currentPage}};
				}}
				if (component.hasMore === false) {{
					return {{ok: false, exhausted: true, reason: 'the page reports no more jobs'}};
				}}
				const beforeCount = jobs.length;
				component.loadMoreHandle();
				return {{ok: true, beforeCount}};
				}})()""",
				workspace="boss-radar",
			)
			if trigger.get("ok"):
				break
			if trigger.get("risk"):
				self._preserve_bridge_window = True
				raise BridgeAccountRiskError(str(trigger.get("reason") or "BOSS 页面要求安全验证"))
			if trigger.get("exhausted"):
				return {"code": 0, "zpData": {"jobList": [], "hasMore": False}}
			reason = str(trigger.get("reason") or "unknown error")
			if reason != "job list loader is unavailable" or time.monotonic() >= component_deadline:
				raise RuntimeError(f"Bridge page loader failed for page {page}: {reason}")
			time.sleep(_JOB_LIST_LOAD_POLL_SECONDS)
		if trigger.get("alreadyLoaded"):
			items = trigger.get("items")
			if not isinstance(items, list):
				raise RuntimeError(f"Bridge page loader returned invalid jobs for page {page}")
			return {"code": 0, "zpData": {"jobList": items, "hasMore": bool(trigger.get("hasMore"))}}

		before_count = int(trigger.get("beforeCount") or 0)
		deadline = time.monotonic() + _JOB_LIST_LOAD_TIMEOUT_SECONDS
		while True:
			state = self._bridge_client.evaluate(
				f"""(() => {{
					const text = document.body?.innerText || '';
					if (/安全验证|验证码|拖动滑块|环境存在异常|账户存在异常行为|暂时被禁止使用|访问过于频繁|稍后再试/.test(text)
						|| /verify[.]html|[?&]code=(32|36|37)(?:&|$)/.test(location.href)) {{
						return {{ready: false, risk: true, reason: 'BOSS security verification detected'}};
					}}
					{_JOB_LIST_COMPONENT_LOOKUP_JS}
					if (!component) return {{ready: false, componentAvailable: false}};
					const form = component.formData || {{}};
					const pageUrl = new URL(location.href);
					const urlMatches = pageUrl.searchParams.get('city') === {expected_city}
						&& pageUrl.searchParams.get('query') === {expected_query};
					const matches = urlMatches && String(form.city || '') === {expected_city}
						&& String(form.query || '') === {expected_query};
					if (!matches) return {{ready: false, stateError: 'visible search state does not match the requested city and query'}};
					const jobs = Array.isArray(component.jobList) ? component.jobList : [];
					const currentPage = Number(component.pageVo?.page || 0);
					const pageSize = Number(component.pageVo?.pageSize || 15);
					const loading = Boolean(component.moreLoading);
					const hasMore = Boolean(component.hasMore);
					const progressed = jobs.length > {before_count} || (currentPage >= {page} && !hasMore);
					if (currentPage >= {page} && !loading && progressed) {{
						const start = ({page} - 1) * pageSize;
						const items = jobs.slice(start, start + pageSize);
						if (items.length === 0) {{
							return {{ready: false, stateError: 'requested page slice is empty after page state advanced'}};
						}}
						return {{
							ready: true,
							items,
							hasMore: currentPage > {page} || hasMore,
						}};
					}}
					return {{ready: false, currentPage, count: jobs.length, loading, hasMore}};
				}})()""",
				workspace="boss-radar",
			)
			if state.get("risk"):
				self._preserve_bridge_window = True
				raise BridgeAccountRiskError(str(state.get("reason") or "BOSS 页面要求安全验证"))
			if state.get("stateError"):
				raise RuntimeError(f"Bridge page loader failed for page {page}: {state['stateError']}")
			if state.get("ready"):
				items = state.get("items")
				if not isinstance(items, list):
					raise RuntimeError(f"Bridge page loader returned invalid jobs for page {page}")
				return {"code": 0, "zpData": {"jobList": items, "hasMore": bool(state.get("hasMore"))}}
			if time.monotonic() >= deadline:
				raise RuntimeError(
					f"Bridge page loader timed out for page {page}; "
					f"componentAvailable={state.get('componentAvailable', True)} "
					f"currentPage={state.get('currentPage')} count={state.get('count')}"
				)
			time.sleep(_JOB_LIST_LOAD_POLL_SECONDS)

	# ── Arbitrary JS evaluation (CDP-only, raw websocket) ────────────

	def evaluate_js(self, script: str, arg: Any = None) -> Any:
		"""Run JS in the user's recruiter chat tab via raw CDP websocket.

		Required for recruiter send_message (issue #217): we reach into the
		招聘者 chat page's Vue 2 instance to call geek-list.geekClick() +
		editor.sendText(). The normal BrowserSession.request fetch path can't
		do that — it runs JS in a blank tab BrowserSession owns, not in the
		user's recruiter tab.

		Why raw CDP instead of patchright: attaching patchright to another
		tab we didn't create via new_page() triggers 'Frame was detached'
		errors when that page navigates or re-renders (Vue SFC rebuilds
		frame tree). Raw CDP is a stateless RPC — we just send
		Runtime.evaluate and read the result, no session book-keeping.

		Intentionally does NOT call _ensure_started(): patchright's
		connect_over_cdp enumerates every tab's frame tree on attach, which
		can race with Vue re-renders on the recruiter page and crash the
		Node driver before we even get to our evaluate call. evaluate_js
		only needs the CDP HTTP endpoint reachable — not patchright.

		Only works in CDP mode (user has chrome://<devtools port>/json
		reachable and the recruiter chat tab open). Bridge/headless modes
		have no access to the user's Vue runtime.
		"""
		if self._is_bridge:
			raise RuntimeError("evaluate_js requires CDP mode (bridge mode has no access to user Chrome)")
		self._require_cdp_source("evaluate_js")
		cdp_url = self._cdp_url or CDP_DEFAULT_URL
		return _cdp_evaluate_in_chat_tab(cdp_url, script, arg)

	def evaluate_js_with_chat_events(self, script: str, arg: Any = None, *, listen_ms: int = 3000) -> dict[str, Any]:
		"""Run JS in the recruiter chat tab and collect short-lived chat WS events.

		Used by recruiter send_message verification to distinguish a real chat send
		from UI-only draft mutation or suggestion traffic.
		"""
		if self._is_bridge:
			raise RuntimeError(
				"evaluate_js_with_chat_events requires CDP mode (bridge mode has no access to user Chrome)"
			)
		self._require_cdp_source("evaluate_js_with_chat_events")
		cdp_url = self._cdp_url or CDP_DEFAULT_URL
		return _cdp_evaluate_with_chat_events_in_chat_tab(cdp_url, script, arg, listen_ms=listen_ms)

	def _require_cdp_source(self, api: str) -> None:
		"""裸 CDP 路径的来源守卫。

		``evaluate_js`` 系列刻意绕过 ``_ensure_started``（见上方 docstring：
		patchright 附着别人的 tab 会撞 'Frame was detached'），所以它不受
		分发器约束——这是本类最大的 fail-open 面：一个禁用了 CDP 的来源，
		在这条路上照样会直连 ``CDP_DEFAULT_URL``。此处补上等价守卫。
		"""
		if not self._policy.allows(CHANNEL_CDP):
			raise BrowserSourceUnavailable(
				self._policy,
				(CHANNEL_CDP,),
				detail=f"{api} 需要 CDP 通道，而 browser-source={self._policy.name} 不允许",
			)
		if not self._policy.auto_probe_cdp and not self._cdp_url:
			raise BrowserSourceUnavailable(
				self._policy,
				(CHANNEL_CDP,),
				detail=f"{api} 需要显式 --cdp-url（browser-source={self._policy.name} 不自动探测端点）",
			)

	# ── Lifecycle ────────────────────────────────────────────────────

	@property
	def is_cdp(self) -> bool:
		"""Whether this session is using CDP connection to user's Chrome."""
		return self._is_cdp

	def close(self) -> None:
		if not self._started:
			# 已关闭 / 从未成功启动：只确保 driver 不泄漏，不重复拆卸。
			# 真正的幂等守卫——否则第二次 close 会因为 _reset_channel_state 已把
			# _is_cdp 置 False 而走进 headless 分支，对一个 CDP 会话执行错误的拆卸。
			self._release_playwright()
			return

		if self._is_bridge and self._bridge_client:
			if not self._preserve_bridge_window:
				try:
					self._bridge_client.close_window()
				except Exception:
					pass
			self._bridge_client = None
			self._reset_channel_state()
			self._preserve_bridge_window = False
			return

		if self._is_cdp:
			# CDP 模式：只关闭独立自动化 page；复用的用户 context 和所有用户页签均不动
			if self._page and self._own_page:
				try:
					self._page.close()
				except Exception:
					pass
			if self._own_context and self._context:
				try:
					self._context.close()
				except Exception:
					pass
		else:
			# Headless 模式：关闭整个浏览器实例或持久 context
			if self._browser:
				try:
					self._browser.close()
				except Exception:
					pass
		self._release_playwright()
		self._reset_channel_state()

	def _reset_channel_state(self) -> None:
		"""close 后把**通道标志**复位到「从未启动」。

		修既有缺陷：原实现只置 ``_started = False``，``_is_cdp`` / ``_is_bridge``
		留着上一轮的值。于是 close 之后再调 ``request()`` 会带着陈旧标志重跑整条链
		——例如上一轮走 Bridge、重连落到 CDP 时 ``_is_bridge`` 仍为 True，
		``request()`` 就会走错分支去调一个已被置空的 ``_bridge_client``。

		刻意**不**清 ``_page`` / ``_context`` / ``_browser``：它们在重启时由
		``_try_connect`` / ``_start_headless`` 的每个分支无条件覆盖，而清空会让
		「close 之后仍可检视上一轮句柄」这个既有性质消失（多条既有测试依赖它）。
		``_policy`` 同样不复位：它是构造期决定的来源意图，不属于通道状态。
		"""
		self._started = False
		self._is_cdp = False
		self._is_bridge = False

	def __enter__(self) -> "BrowserSession":
		return self

	def __exit__(
		self,
		exc_type: type[BaseException] | None,
		exc_val: BaseException | None,
		exc_tb: TracebackType | None,
	) -> None:
		self.close()


