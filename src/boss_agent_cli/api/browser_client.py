def _is_zhipin_url(url: str) -> bool:
	"""Only zhipin.com and its subdomains are reusable browser pages."""
	host = urlparse(url).hostname
	if host is None:
		return False
	host = host.rstrip(".").lower()
	return host == _ZHIPIN_HOST or host.endswith(f".{_ZHIPIN_HOST}")


def _find_reusable_zhipin_page(context: Any) -> Any | None:
	"""Return the first already-open Zhipin page in a browser context."""
	for page in getattr(context, "pages", None) or []:
		if _is_zhipin_url(getattr(page, "url", "")):
			return page
	return None


def _is_bridge_account_risk(message: str) -> bool:
	"""Recognize explicit BOSS verification evidence without matching false signals."""
	lower = message.lower().replace(" ", "")
	return any(
		marker in lower
		for marker in (
			"verify.html",
			'captchasignal":true',
			"安全验证",
			"环境存在异常",
			"账户存在异常行为",
			"暂时被禁止使用",
			"captcha_required",
			"captcharequired",
			"code=32",
			"code=36",
			"code=37",
			'"code":32',
			'"code":37',
		)
	)


def _radar_tab_url_matches_search(status: Any, expected_url: str) -> bool:
	"""Return true only for an already-settled equivalent BOSS results URL.

	BOSS may append transient tracking or security-check parameters after an
	ordinary navigation. Those extra parameters do not change the selected city
	or keyword. This helper is used only to permit a read-only recovery after a
	fresh navigation has already happened.
	"""
	if not isinstance(status, dict):
		return False
	current_url = status.get("url")
	if not isinstance(current_url, str) or not current_url:
		return False
	current = urlparse(current_url)
	expected = urlparse(expected_url)
	if (
		current.scheme != "https"
		or current.hostname is None
		or current.hostname.rstrip(".").lower() != "www.zhipin.com"
	):
		return False
	current_query = parse_qs(current.query, keep_blank_values=True)
	expected_query = parse_qs(expected.query, keep_blank_values=True)
	if expected.path.startswith("/c"):
		return (
			current.path.rstrip("/") == expected.path.rstrip("/")
			and current_query.get("query") == expected_query.get("query")
			and len(current_query.get("query", [])) == 1
		)
	if current.path != "/web/geek/jobs":
		return False
	return (
		current_query.get("city") == expected_query.get("city")
		and current_query.get("query") == expected_query.get("query")
		and len(current_query.get("city", [])) == 1
		and len(current_query.get("query", [])) == 1
	)


_MIN_RADAR_BRIDGE_VERSION = (1, 2, 34)


def _bridge_version_at_least(version: str, minimum: tuple[int, int, int]) -> bool:
	"""Compare the numeric core of a Bridge extension version."""
	core = version.strip().split("+", 1)[0].split("-", 1)[0]
	parts = core.split(".")
	if not parts or any(not part.isdigit() for part in parts):
		return False
	numbers = tuple(int(part) for part in parts[:3])
	padded = numbers + (0,) * (3 - len(numbers))
	return padded >= minimum


