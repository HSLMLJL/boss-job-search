def _validated_visible_capture(result: Any, *, page: int) -> dict[str, Any]:
	"""Reject an ambiguous visible-page read before scanner terminal handling."""
	if not isinstance(result, dict):
		raise RuntimeError("Bridge visible job capture returned a non-object response")
	data = result.get("zpData")
	if type(result.get("code")) is not int or result["code"] != 0 or not isinstance(data, dict):
		raise RuntimeError("Bridge visible job capture returned an invalid success envelope")
	items = data.get("jobList")
	has_more = data.get("hasMore")
	if not isinstance(items, list) or type(has_more) is not bool:
		raise RuntimeError("Bridge visible job capture requires jobList and boolean hasMore")
	page_state = data.get("pageState")
	if not isinstance(page_state, dict):
		raise RuntimeError("Bridge visible job capture requires same-page state evidence")
	if type(page_state.get("currentPage")) is not int or page_state["currentPage"] != page:
		raise RuntimeError("Bridge visible job capture state has an unexpected page")
	if page_state.get("identityMatched") is not True:
		raise RuntimeError("Bridge visible job capture state does not match the requested search")
	if type(page_state.get("hasMore")) is not bool or page_state["hasMore"] is not has_more:
		raise RuntimeError("Bridge visible job capture state hasMore does not match the captured page")
	page_size = page_state.get("pageSize")
	if page_size is not None and (type(page_size) is not int or not 1 <= page_size <= 100):
		raise RuntimeError("Bridge visible job capture state has an invalid page size")
	if not items and not has_more:
		if page_state.get("terminal") is not True:
			raise RuntimeError("Bridge visible job capture has no explicit empty-page terminal evidence")
	return result


